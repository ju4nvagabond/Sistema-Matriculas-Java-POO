    // AQUÍ ESTÁN LOS MÉTODOS Y LA LÓGICA PERSONALIZADA 
  
    private void asignarEventos() {
        btnAgregar.addActionListener(e -> agregarMateria());
        btnEliminar.addActionListener(e -> eliminarMateria());
        btnVolver.addActionListener(e -> {
            new PantallaPrincipal().setVisible(true);
            this.dispose();
        });
    }

    private void cargarDatosTabla() {
        String[] columnas = {"Código", "Nombre", "Cupos Totales", "Cupos Restantes", "Estado"};
        
        javax.swing.table.DefaultTableModel modeloTabla = new javax.swing.table.DefaultTableModel(columnas, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false; 
            }
        };

        Object[][] datos = Logica.GestorDatos.getMatrizMaterias();
        for (Object[] fila : datos) {
            modeloTabla.addRow(fila);
        }

        jTable1.setModel(modeloTabla);
    }

    private void agregarMateria() {
        String codigo = txtCodigo.getText().trim();
        String nombre = txtNombre.getText().trim();
        String cuposTexto = txtCupos.getText().trim();

        if (codigo.isEmpty() || nombre.isEmpty() || cuposTexto.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor complete todos los campos.", "Advertencia", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            int cupos = Integer.parseInt(cuposTexto);
            if (director != null && director.agregarMateria(codigo, nombre, cupos)) {
                javax.swing.JOptionPane.showMessageDialog(this, "Materia agregada con éxito.");
                txtCodigo.setText("");
                txtNombre.setText("");
                txtCupos.setText("");
                cargarDatosTabla();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "El código de materia ya existe o no hay permisos.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Los cupos deben ser un número válido.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }

    private void eliminarMateria() {
        int filaSeleccionada = jTable1.getSelectedRow();
        if (filaSeleccionada >= 0) {
            String codigo = jTable1.getValueAt(filaSeleccionada, 0).toString();
            int confirm = javax.swing.JOptionPane.showConfirmDialog(this, "¿Seguro que desea eliminar la materia " + codigo + "?", "Confirmar", javax.swing.JOptionPane.YES_NO_OPTION);
            if (confirm == javax.swing.JOptionPane.YES_OPTION) {
                if (director != null && director.eliminarMateria(codigo)) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Materia eliminada.");
                    cargarDatosTabla();
                }
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Seleccione una materia de la tabla para eliminar.", "Advertencia", javax.swing.JOptionPane.WARNING_MESSAGE);
        }
    }

    


